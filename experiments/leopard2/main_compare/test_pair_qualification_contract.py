MODULE_PATH = pathlib.Path(__file__).with_name("pair_qualification_contract.py")
SPEC = importlib.util.spec_from_file_location(
    "leopard_pair_qualification_contract_under_test", MODULE_PATH,
)
if SPEC is None or SPEC.loader is None:
    raise RuntimeError("cannot load pair qualification contract")
contract = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(contract)


CPU_IDS = [3, 7, 10, 20, 30, 40]
DOMAIN = list(CPU_IDS)
BASE_NS = 1_000_000_000
READ_NS = 100_000


def counter_fields(**overrides: int) -> dict[str, int]:
    result = {
        "user": 0,
        "nice": 0,
        "system": 0,
        "idle": 0,
        "iowait": 0,
        "irq": 0,
        "softirq": 0,
        "steal": 0,
    }
    result.update(overrides)
    return result


def policy_fixture(domain_mode: str = "pair-only") -> dict:
    # Kept literal rather than generated by qualification_policy_record so the
    # validator is exercised against an independent golden policy object.
    return {
        "schema": "leopard2-pair-qualification-policy/v1",
        "clock_ticks_per_second": 100,
        "candidate_primary_cpus": [7, 10, 30],
        "excluded_pairs": [{
            "benchmark_cpu": 30,
            "reserved_sibling": 40,
            "reason": "fixture policy exclusion",
        }],
        "domain_mode": domain_mode,
        "candidate_rule": "explicit-primary-symmetric-smt2-online-allowed/v1",
        "selection_rule": "lowest-primary-unless-frozen/v1",
        "frozen_pair_rule": "require-frozen-when-present-no-fallback/v1",
        "observation": {
            "counter_source": "/proc/stat",
            "counter_fields": [
                "user", "nice", "system", "idle", "iowait", "irq",
                "softirq", "steal",
            ],
            "idle_fields": ["idle", "iowait"],
            "nonidle_fields": [
                "user", "nice", "system", "irq", "softirq", "steal",
            ],
            "tick_cap_formula": (
                "(elapsed_ns * clock_ticks_per_second) // 1000000000 + 1"
            ),
            "liveness_lower_slack_jiffies": 2,
            "nonidle_limit_jiffies": 0,
            "liveness_rule": (
                "narrow_tick_cap - 2 >= 1 and narrow_tick_cap - 2 <= "
                "total_jiffies_delta <= wide_tick_cap"
            ),
        },
    }


def topology_fixture() -> dict:
    pair_by_cpu = {
        3: (3, 7, 1),
        7: (3, 7, 1),
        10: (10, 20, 2),
        20: (10, 20, 2),
        30: (30, 40, 3),
        40: (30, 40, 3),
    }
    return {
        "schema": "leopard2-pair-qualification-topology/v1",
        "cpus": [{
            "cpu": cpu,
            "online": True,
            "physical_package_id": 0,
            "die_id": 0,
            "core_id": pair_by_cpu[cpu][2],
            "thread_siblings": list(pair_by_cpu[cpu][:2]),
            "domain_cpus": list(DOMAIN),
        } for cpu in CPU_IDS],
    }


def snapshot(
    index: int,
    *,
    events: dict[int, str] | None = None,
    stalled_cpus: set[int] | None = None,
    total_overrides: dict[int, int] | None = None,
    started_ns: int | None = None,
    finished_ns: int | None = None,
) -> dict:
    events = events or {}
    stalled_cpus = stalled_cpus or set()
    total_overrides = total_overrides or {}
    if started_ns is None:
        started_ns = BASE_NS + index * 250_100_000
    if finished_ns is None:
        finished_ns = started_ns + READ_NS
    counters: dict[int, dict[str, int]] = {}
    for cpu in CPU_IDS:
        if cpu in stalled_cpus:
            total = 100
        else:
            total = 100 + 25 * index
        total = total_overrides.get(cpu, total)
        fields = counter_fields(idle=total)
        event_field = events.get(cpu)
        if event_field is not None and index > 0:
            fields["idle"] -= 1
            fields[event_field] += 1
        counters[cpu] = fields
    return contract.shared_snapshot_record(
        read_started_monotonic_ns=started_ns,
        read_finished_monotonic_ns=finished_ns,
        counters=counters,
    )


def snapshots(
    *,
    events: dict[int, str] | None = None,
    stalled_cpus: set[int] | None = None,
) -> list[dict]:
    return [
        snapshot(index, events=events, stalled_cpus=stalled_cpus)
        for index in range(3)
    ]


def scan_fixture(
    *,
    policy: dict | None = None,
    endpoint_records: list[dict] | None = None,
    frozen: dict | None = None,
    allowed: list[int] | None = None,
) -> dict:
    if policy is None:
        policy = policy_fixture()
    if endpoint_records is None:
        endpoint_records = snapshots()
    if allowed is None:
        allowed = list(CPU_IDS)
    topology = topology_fixture()
    return contract.pair_qualification_scan_record(
        policy,
        allowed_cpu_set_at_launch=allowed,
        topology_before=topology,
        topology_after=copy.deepcopy(topology),
        snapshots=endpoint_records,
        frozen_pair_from_prior_attempt=frozen,
    )


class PairQualificationContractTests(unittest.TestCase):
    def assertRejected(self, function, pattern: str | None = None) -> None:
        with self.assertRaises(contract.QualificationError) as raised:
            function()
        if pattern is not None:
            self.assertIn(pattern, str(raised.exception))

    def test_literal_policy_and_strict_singleton_json(self) -> None:
        policy = policy_fixture()
        self.assertEqual(contract.validate_qualification_policy(policy), policy)
        encoded = contract.canonical_json_bytes(policy)
        self.assertEqual(contract.strict_json_loads(encoded), policy)
        for payload in (
            b'{"x":1,"x":2}',
            b'{"x":NaN}',
            b'{"x":Infinity}',
            b'{"x":1e309}',
            b'{}\n{}',
            b'[' * 10_000 + b']' * 10_000,
            b'',
            b'\xff',
        ):
            with self.subTest(payload=payload):
                self.assertRejected(lambda payload=payload: contract.strict_json_loads(payload))

    def test_policy_exact_types_keys_order_and_input_immutability(self) -> None:
        policy = policy_fixture()
        for path, value in (
            (("clock_ticks_per_second",), True),
            (("clock_ticks_per_second",), 100.0),
            (("candidate_primary_cpus",), [10, 7, 30]),
            (("observation", "nonidle_limit_jiffies"), 1),
            (("domain_mode",), "quietest"),
        ):
            mutated = copy.deepcopy(policy)
            target = mutated
            for key in path[:-1]:
                target = target[key]
            target[path[-1]] = value
            with self.subTest(path=path, value=value):
                self.assertRejected(lambda mutated=mutated: contract.validate_qualification_policy(mutated))
        extra = copy.deepcopy(policy)
        extra["score"] = 0
        self.assertRejected(lambda: contract.validate_qualification_policy(extra))
        for unsafe_character in ("\ud800", "\u0085", "\u009f", "\u200e", "\u2028", "\ufeff"):
            unsafe_reason = copy.deepcopy(policy)
            unsafe_reason["excluded_pairs"][0]["reason"] = (
                f"bad{unsafe_character}reason"
            )
            with self.subTest(unsafe_character=repr(unsafe_character)):
                self.assertRejected(
                    lambda unsafe_reason=unsafe_reason: (
                        contract.validate_qualification_policy(unsafe_reason)
                    )
                )
        stable_reason = copy.deepcopy(policy)
        stable_reason["excluded_pairs"][0]["reason"] = "stable\U00013439reason"
        contract.validate_qualification_policy(stable_reason)
        duplicate_exclusion = copy.deepcopy(policy["excluded_pairs"])
        duplicate_exclusion.append({
            "benchmark_cpu": 30,
            "reserved_sibling": 3,
            "reason": "second spelling of one excluded primary",
        })
        self.assertRejected(lambda: contract.qualification_policy_record(
            clock_ticks_per_second=100,
            candidate_primary_cpus=policy["candidate_primary_cpus"],
            excluded_pairs=duplicate_exclusion,
            domain_mode="pair-only",
        ), "duplicate excluded candidate primary")
        source_primaries = [30, 7, 10]
        source_exclusions = copy.deepcopy(policy["excluded_pairs"])
        before = copy.deepcopy((source_primaries, source_exclusions))
        generated = contract.qualification_policy_record(
            clock_ticks_per_second=100,
            candidate_primary_cpus=source_primaries,
            excluded_pairs=source_exclusions,
            domain_mode="pair-only",
        )
        self.assertEqual((source_primaries, source_exclusions), before)
        self.assertEqual(generated, policy)

        unsorted_exclusions = [
            copy.deepcopy(policy["excluded_pairs"][0]),
            {
                "benchmark_cpu": 7,
                "reserved_sibling": 3,
                "reason": "second fixture exclusion",
            },
        ]
        two_exclusion_policy = contract.qualification_policy_record(
            clock_ticks_per_second=100,
            candidate_primary_cpus=policy["candidate_primary_cpus"],
            excluded_pairs=unsorted_exclusions,
            domain_mode="pair-only",
        )
        self.assertEqual(
            [item["benchmark_cpu"] for item in two_exclusion_policy["excluded_pairs"]],
            [7, 30],
        )
        noncanonical_exclusions = copy.deepcopy(two_exclusion_policy)
        noncanonical_exclusions["excluded_pairs"].reverse()
        self.assertRejected(
            lambda: contract.validate_qualification_policy(noncanonical_exclusions),
            "not canonical",
        )

    def test_topology_is_symmetric_and_does_not_assume_plus_64(self) -> None:
        topology = topology_fixture()
        self.assertEqual(contract.validate_topology(topology), topology)
        candidates = contract.derive_candidate_pairs(policy_fixture(), topology, CPU_IDS)
        self.assertEqual(candidates, [
            {"benchmark_cpu": 7, "reserved_sibling": 3, "domain_cpus": DOMAIN},
            {"benchmark_cpu": 10, "reserved_sibling": 20, "domain_cpus": DOMAIN},
        ])
        self.assertGreater(candidates[0]["benchmark_cpu"], candidates[0]["reserved_sibling"])

        mutations = []
        asymmetric = copy.deepcopy(topology)
        asymmetric["cpus"][0]["thread_siblings"] = [3]
        mutations.append(asymmetric)
        wrong_core = copy.deepcopy(topology)
        wrong_core["cpus"][1]["core_id"] = 99
        mutations.append(wrong_core)
        wrong_package = copy.deepcopy(topology)
        wrong_package["cpus"][1]["physical_package_id"] = 1
        mutations.append(wrong_package)
        duplicate_core_identity = copy.deepcopy(topology)
        duplicate_core_identity["cpus"][2]["core_id"] = 1
        duplicate_core_identity["cpus"][3]["core_id"] = 1
        mutations.append(duplicate_core_identity)
        wrong_domain = copy.deepcopy(topology)
        wrong_domain["cpus"][1]["domain_cpus"] = [7]
        mutations.append(wrong_domain)
        split_sibling_domain = copy.deepcopy(topology)
        split_sibling_domain["cpus"][0]["domain_cpus"] = [3]
        split_sibling_domain["cpus"][1]["domain_cpus"] = [7]
        mutations.append(split_sibling_domain)
        three_way = copy.deepcopy(topology)
        three_way["cpus"][0]["thread_siblings"] = [3, 7, 10]
        mutations.append(three_way)
        for index, mutated in enumerate(mutations):
            with self.subTest(index=index):
                self.assertRejected(lambda mutated=mutated: contract.validate_topology(mutated))

    def test_candidate_enumeration_applies_allowed_set_and_exact_exclusion(self) -> None:
        policy = policy_fixture()

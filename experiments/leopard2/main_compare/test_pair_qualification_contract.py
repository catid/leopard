    def test_short_window_and_stalled_counter_fail_closed(self) -> None:
        policy = policy_fixture()
        before = snapshot(0, started_ns=BASE_NS, finished_ns=BASE_NS + READ_NS)
        after = snapshot(
            0,
            started_ns=BASE_NS + READ_NS + 10_000_000,
            finished_ns=BASE_NS + 2 * READ_NS + 10_000_000,
        )
        window = contract.pair_observation_window_record(
            policy,
            phase="bridge",
            index=0,
            before=before,
            after=after,
            observed_cpus=CPU_IDS,
        )
        self.assertEqual(window["elapsed_tick_cap"], 2)
        self.assertEqual(window["liveness_lower_bound_jiffies"], 0)
        self.assertEqual(window["not_live_cpus"], CPU_IDS)
        stalled = scan_fixture(endpoint_records=snapshots(stalled_cpus={3}))
        pair = next(item for item in stalled["candidate_pairs"] if item["benchmark_cpu"] == 7)
        self.assertFalse(pair["pair_live"])
        self.assertFalse(pair["qualified"])

